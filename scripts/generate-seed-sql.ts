/**
 * Turns the TypeScript sample seed into SQL for Supabase.
 *   node scripts/generate-seed-sql.ts > supabase/seed/sample_content.sql
 * (Node 22.18+ runs .ts files directly.) Re-run it whenever the sample seed changes, then run the
 * resulting SQL against Supabase. It targets the CURRENT schema (after migration 0004) and upserts,
 * so it is safe to re-run. The old migrations/0002 file is kept only as history.
 */
import { placesSeed } from '../src/data/mock/places.seed.ts'
import { trailsSeed } from '../src/data/mock/trails.seed.ts'

// Dollar-quoting means we never have to escape apostrophes in story text.
const q = (value: string): string => `$tt$${value}$tt$`
const qOrNull = (value: string | undefined): string => (value === undefined ? 'null' : q(value))
const textArray = (values: string[]): string => `array[${values.map(q).join(', ')}]::text[]`
const enumArray = (values: string[], type: string): string =>
  `array[${values.map((v) => `'${v}'`).join(', ')}]::public.${type}[]`

const lines: string[] = [
  '-- Table Tales: SAMPLE (fictional) content. Generated by scripts/generate-seed-sql.ts.',
  '-- Every row is a placeholder (is_placeholder = true). Safe to re-run: it upserts.',
  '',
]

for (const place of placesSeed) {
  lines.push(
    `insert into public.places (id, name, neighborhood, cuisine, price_tier, tags, summary, source_label, mock_distance_miles, is_placeholder) values (`,
    `  ${q(place.id)}, ${q(place.name)}, ${q(place.neighborhood)}, ${q(place.cuisine)}, ${place.priceTier},`,
    `  ${enumArray(place.tags, 'story_tag')}, ${q(place.summary)}, '${place.sourceLabel}',`,
    `  ${place.mockDistanceMiles}, ${place.isPlaceholder}`,
    `) on conflict (id) do update set name = excluded.name, neighborhood = excluded.neighborhood,`,
    `  cuisine = excluded.cuisine, price_tier = excluded.price_tier, tags = excluded.tags,`,
    `  summary = excluded.summary, source_label = excluded.source_label,`,
    `  mock_distance_miles = excluded.mock_distance_miles, is_placeholder = excluded.is_placeholder;`,
    `insert into public.place_details (place_id, order_dish, order_why, ask_them) values (${q(place.id)}, ${q(place.whatToOrder.dish)}, ${q(place.whatToOrder.why)}, ${textArray(place.askThem)})`,
    `  on conflict (place_id) do update set order_dish = excluded.order_dish, order_why = excluded.order_why, ask_them = excluded.ask_them;`,
  )
  place.sections.forEach((section, index) => {
    lines.push(
      `insert into public.place_sections (place_id, kind, title, body, sort_order) values (${q(place.id)}, '${section.kind}', ${q(section.title)}, ${textArray(section.body)}, ${index + 1})`,
      `  on conflict (place_id, kind) do update set title = excluded.title, body = excluded.body, sort_order = excluded.sort_order;`,
    )
  })
  lines.push(`delete from public.place_sources where place_id = ${q(place.id)};`)
  place.sources.forEach((source, index) => {
    lines.push(
      `insert into public.place_sources (place_id, label, kind, note, sort_order) values (${q(place.id)}, ${q(source.label)}, '${source.kind}', ${qOrNull(source.note)}, ${index + 1});`,
    )
  })
  lines.push('')
}

for (const trail of trailsSeed) {
  lines.push(
    `insert into public.trails (id, title, kind, area, description, estimated_minutes, is_placeholder) values (`,
    `  ${q(trail.id)}, ${q(trail.title)}, '${trail.kind}', ${q(trail.area)}, ${q(trail.description)}, ${trail.estimatedMinutes}, ${trail.isPlaceholder}`,
    `) on conflict (id) do update set title = excluded.title, kind = excluded.kind, area = excluded.area,`,
    `  description = excluded.description, estimated_minutes = excluded.estimated_minutes, is_placeholder = excluded.is_placeholder;`,
    `delete from public.trail_stops where trail_id = ${q(trail.id)};`,
  )
  for (const stop of trail.stops) {
    lines.push(
      `insert into public.trail_stops (trail_id, stop_order, place_id, blurb, from_previous) values (${q(trail.id)}, ${stop.order}, ${q(stop.placeId)}, ${q(stop.blurb)}, ${qOrNull(stop.fromPrevious)});`,
    )
  }
  lines.push('')
}

process.stdout.write(lines.join('\n'))
